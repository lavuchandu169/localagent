#!/usr/bin/env node
// Writes src/electron/embeddedCredentials.ts from the GOOGLE_OAUTH_CLIENT_ID_EMBED
// build-time environment variable, so official release builds ship a working
// Google Client ID with no setup required — while every local/from-source
// build (where this var is never set) gets `null` and falls back to the
// existing Settings-panel / .env paths exactly as before.
//
// Deliberately a distinct name from GOOGLE_OAUTH_CLIENT_ID: that one is the
// *runtime* env var a developer sets to override everything (see
// resolveGoogleCredentials in googleSettings.ts) — this one only ever exists
// at build time, in CI, and never on an end user's machine.
//
// Runs as the first step of `npm run build`, before `tsc`, so the generated
// file always exists when the compiler reaches it.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(__dirname, "..", "src", "electron", "embeddedCredentials.ts");

const clientId = process.env.GOOGLE_OAUTH_CLIENT_ID_EMBED || null;

const contents = `// Generated by scripts/generate-embedded-credentials.mjs at build time — do not edit or commit.
export const EMBEDDED_GOOGLE_CLIENT_ID: string | null = ${clientId ? JSON.stringify(clientId) : "null"};
`;

await fs.writeFile(outFile, contents, "utf-8");
console.log(`[build] wrote ${path.relative(process.cwd(), outFile)} (embedded client id: ${clientId ? "present" : "none"})`);
