#!/usr/bin/env node
// Writes src/electron/embeddedCredentials.ts from the GOOGLE_OAUTH_CLIENT_ID_EMBED
// / GOOGLE_OAUTH_CLIENT_SECRET_EMBED build-time environment variables, so
// official release builds ship working Google credentials with no setup
// required — while every local/from-source build (where these vars are
// never set) gets `null` and falls back to the existing Settings-panel /
// .env paths exactly as before.
//
// Deliberately distinct names from GOOGLE_OAUTH_CLIENT_ID/_SECRET: those are
// the *runtime* env vars a developer sets to override everything (see
// resolveGoogleCredentials in googleSettings.ts) — these two only ever exist
// at build time, in CI, and never on an end user's machine. Embedding the
// secret is safe per Google/RFC 8252's own guidance for installed apps: a
// native app's client secret can't be kept confidential (every copy of the
// app ships it), which is exactly why this app's OAuth flow already uses
// PKCE regardless of whether a secret is present.
//
// Runs as the first step of `npm run build`, before `tsc`, so the generated
// file always exists when the compiler reaches it.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(__dirname, "..", "src", "electron", "embeddedCredentials.ts");

const clientId = process.env.GOOGLE_OAUTH_CLIENT_ID_EMBED || null;
const clientSecret = process.env.GOOGLE_OAUTH_CLIENT_SECRET_EMBED || null;

const contents = `// Generated by scripts/generate-embedded-credentials.mjs at build time — do not edit or commit.
export const EMBEDDED_GOOGLE_CLIENT_ID: string | null = ${clientId ? JSON.stringify(clientId) : "null"};
export const EMBEDDED_GOOGLE_CLIENT_SECRET: string | null = ${clientSecret ? JSON.stringify(clientSecret) : "null"};
`;

await fs.writeFile(outFile, contents, "utf-8");
console.log(
  `[build] wrote ${path.relative(process.cwd(), outFile)} (embedded client id: ${clientId ? "present" : "none"}, secret: ${clientSecret ? "present" : "none"})`
);
